-- Bitácora de cada llamada de confirmación de asistencia (poligrafía/visita) — antes,
-- estado_confirmacion/notas_confirmacion en servicio_subprocesos se sobrescribían con cada
-- llamada nueva, perdiendo el rastro de intentos anteriores (ej. dos "no contesta" antes de un
-- "confirmado"). Log de solo-inserción, igual que historial_asignaciones.
CREATE TABLE historial_llamadas_confirmacion (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio_subproceso  BIGINT NOT NULL REFERENCES servicio_subprocesos (id) ON DELETE CASCADE,
    estado_confirmacion     VARCHAR(20) NOT NULL,
    notas                   TEXT,
    id_actor                BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    fecha_llamada           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ON historial_llamadas_confirmacion (id_servicio_subproceso);
