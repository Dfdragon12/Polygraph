-- Bitácora de cada cambio de asignación de un subproceso (servicio_subprocesos): quién estaba
-- asignado antes, quién queda ahora, y quién hizo el cambio. Log de solo-inserción — nunca se
-- actualiza ni se borra una fila existente. Antes, "Desasignar" pisaba usuario_asignado y
-- fecha_programada con NULL sin dejar ningún rastro de quién había estado asignado.
CREATE TABLE historial_asignaciones (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio_subproceso      BIGINT NOT NULL REFERENCES servicio_subprocesos (id) ON DELETE CASCADE,
    accion                      VARCHAR(20) NOT NULL,
    id_usuario_anterior         BIGINT REFERENCES usuarios (id_usuario),
    id_usuario_nuevo            BIGINT REFERENCES usuarios (id_usuario),
    fecha_programada_anterior   TIMESTAMP,
    fecha_programada_nueva      TIMESTAMP,
    id_actor                    BIGINT REFERENCES usuarios (id_usuario),
    observaciones               TEXT,
    fecha_evento                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ON historial_asignaciones (id_servicio_subproceso);
