-- Fase B del motor de calificación de riesgo (docs/modelo-calificacion-riesgo.md §3): los
-- "hallazgos" son respuestas de la plantilla con puntos.
--
--   formulario_secciones 1 ──< formulario_columnas 1 ──< formulario_columna_puntajes
--                                (califica_riesgo)         (opcion, puntos, es_critico)
--
-- · formulario_columnas.califica_riesgo: el campo (solo Lista o Sí/No) cuenta para el puntaje.
-- · formulario_columna_puntajes: puntos y marca crítica de cada respuesta posible. opcion es el
--   texto exacto de la opción de la lista; en campos Sí/No, 'true' o 'false' (así se guarda el
--   valor en formulario_datos). Una respuesta crítica lleva el subproceso a 100 y el estudio a ALTO.
-- · formulario_datos.justificacion: explicación obligatoria que escribe quien diligencia cuando
--   elige una respuesta crítica (no puede enviar el subproceso sin ella).

ALTER TABLE formulario_columnas
    ADD COLUMN califica_riesgo BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE formulario_columna_puntajes (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_columna  INTEGER      NOT NULL REFERENCES formulario_columnas (id_columna) ON DELETE CASCADE,
    opcion      VARCHAR(200) NOT NULL,
    puntos      NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (puntos >= 0 AND puntos <= 100),
    es_critico  BOOLEAN      NOT NULL DEFAULT false,
    UNIQUE (id_columna, opcion)
);

CREATE INDEX ON formulario_columna_puntajes (id_columna);

ALTER TABLE formulario_datos
    ADD COLUMN justificacion TEXT;
