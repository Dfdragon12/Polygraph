-- Centrales de riesgo configurables (2026-10-22): el indicador de pago (score) de Análisis financiero se ubica en una de las
-- 4 bandas de la central consultada. El nombre de la central es SOLO interno (nunca se imprime): si cambia el proveedor,
-- se ajustan sus bandas aquí y la plantilla no se toca. Admin → Calificación de riesgo → Centrales de riesgo.

CREATE TABLE centrales_riesgo (
    id_central INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE centrales_riesgo_bandas (
    id_banda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_central INTEGER NOT NULL REFERENCES centrales_riesgo (id_central) ON DELETE CASCADE,
    orden INTEGER NOT NULL,
    desde INTEGER NOT NULL,
    hasta INTEGER NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    CONSTRAINT uq_central_banda_orden UNIQUE (id_central, orden)
);

