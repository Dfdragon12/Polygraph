-- Estructura configurable del documento de Verificación de Antecedentes Legales — qué bloques
-- (una categoría de fuentes, o SIMIT/SIMUR/RUNT) aparecen en el Word generado y en qué orden.
-- Se administra desde admin/catálogo/plantilla-antecedente ("¿deseas agregar tabla?" — eliges
-- entre los bloques disponibles y los ordenas). La presencia de una fila = el bloque está
-- incluido en el documento; el valor de orden = su posición.
CREATE TABLE plantilla_antecedentes_bloques (
    id_bloque    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_bloque  VARCHAR(30) NOT NULL,   -- 'FUENTES_CATEGORIA' | 'SIMIT' | 'SIMUR' | 'RUNT'
    categoria    VARCHAR(100),           -- solo cuando tipo_bloque = 'FUENTES_CATEGORIA'
    orden        INTEGER NOT NULL DEFAULT 0
);

-- Estructura por defecto: las categorías que ya existen en el catálogo de fuentes, en su orden
-- natural, seguidas de los tres bloques fijos — el mismo orden que tenía el documento antes de
-- ser configurable, para no cambiar nada hasta que alguien lo edite a propósito.
INSERT INTO plantilla_antecedentes_bloques (tipo_bloque, categoria, orden)
SELECT 'FUENTES_CATEGORIA', categoria, MIN(orden)
FROM catalogo_fuentes_antecedentes
GROUP BY categoria;

