-- NS-02: lotes de la bolsa prepago. Cada compra APROBADA (cada ítem de la orden) es un lote con su cantidad y su valor unitario.
-- Las solicitudes descuentan del lote más antiguo con unidades (FIFO) y guardan en la solicitud QUÉ lote usaron y cuánto valía la unidad:
-- ese valor se guarda una vez y no se recalcula con compras nuevas.
--
-- Los contadores de saldos_servicio_cliente siguen siendo la fuente del disponible (NS-01); los lotes dan el precio y la trazabilidad.
-- Lo que ya existía:
--   1) un lote por cada ítem de orden APROBADA;
--   2) lo ya consumido (cantidad_consumida del saldo) se reparte FIFO entre los lotes del cliente y servicio, del más antiguo al más nuevo;
--   3) las solicitudes de clientes PREPAGO se asocian al lote en el orden en que se crearon (la 1.ª al lote más antiguo...), hasta cubrir lo consumido.
-- Es una reconstrucción: el valor de una solicitud vieja queda en el lote que le habría tocado. Todo queda en migracion_lotes_prepago_reporte.
-- No borra nada. Idempotente.

CREATE TABLE IF NOT EXISTS lotes_prepago (
    id_lote                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente               INTEGER        NOT NULL REFERENCES clientes (id_cliente),
    id_proceso               INTEGER        NOT NULL REFERENCES procesos (id_proceso),
    id_orden_compra          BIGINT         NOT NULL REFERENCES ordenes_compra (id_orden_compra),
    id_item                  BIGINT         NOT NULL UNIQUE REFERENCES orden_compra_items (id_item),
    cantidad_comprada        INTEGER        NOT NULL CHECK (cantidad_comprada > 0),
    cantidad_consumida       INTEGER        NOT NULL DEFAULT 0 CHECK (cantidad_consumida >= 0),
    valor_unitario           NUMERIC(15, 2) NOT NULL,
    valor_original           NUMERIC(15, 2),
    nombre_descuento_aplicado VARCHAR(150),
    fecha_compra             TIMESTAMP      NOT NULL,
    CHECK (cantidad_consumida <= cantidad_comprada)
);
CREATE INDEX IF NOT EXISTS ix_lotes_prepago_fifo ON lotes_prepago (id_cliente, id_proceso, fecha_compra, id_lote);

ALTER TABLE servicios ADD COLUMN IF NOT EXISTS id_lote_prepago BIGINT REFERENCES lotes_prepago (id_lote);
ALTER TABLE servicios ADD COLUMN IF NOT EXISTS valor_unitario_prepago NUMERIC(15, 2);

CREATE TABLE IF NOT EXISTS migracion_lotes_prepago_reporte (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(30)  NOT NULL,   -- LOTE, CONSUMO_SIN_COMPRA, SERVICIO_SIN_LOTE, COMPRA_SIN_SALDO
    id_cliente    INTEGER,
    id_proceso    INTEGER,
    id_lote       BIGINT,
    id_servicio   INTEGER,
    cantidad      INTEGER,
    observacion   VARCHAR(300),
    migrado_en    TIMESTAMP NOT NULL DEFAULT NOW()
);

-- 1) un lote por ítem de orden aprobada
INSERT INTO lotes_prepago (id_cliente, id_proceso, id_orden_compra, id_item, cantidad_comprada, valor_unitario, valor_original, nombre_descuento_aplicado, fecha_compra)
SELECT o.id_cliente, i.id_proceso, o.id_orden_compra, i.id_item, i.cantidad, i.valor_unitario, i.valor_original, i.nombre_descuento_aplicado, o.fecha_actualizacion
FROM orden_compra_items i
JOIN ordenes_compra o ON o.id_orden_compra = i.id_orden_compra
WHERE o.estado = 'APROBADA'
  AND NOT EXISTS (SELECT 1 FROM lotes_prepago l WHERE l.id_item = i.id_item);

-- 2) lo consumido, FIFO: al lote le toca lo que sobre de la cantidad consumida después de llenar los anteriores
WITH acumulado AS (
    SELECT l.id_lote, l.cantidad_comprada,
           COALESCE(SUM(l.cantidad_comprada) OVER (PARTITION BY l.id_cliente, l.id_proceso ORDER BY l.fecha_compra, l.id_lote
                                                  ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) AS antes,
           COALESCE(s.cantidad_consumida, 0) AS consumido
    FROM lotes_prepago l
    LEFT JOIN saldos_servicio_cliente s ON s.id_cliente = l.id_cliente AND s.id_proceso = l.id_proceso
)
UPDATE lotes_prepago l
SET cantidad_consumida = LEAST(a.cantidad_comprada, GREATEST(a.consumido - a.antes, 0))
FROM acumulado a
WHERE a.id_lote = l.id_lote AND l.cantidad_consumida = 0;

-- 3) solicitudes de clientes prepago, en orden de creación, al lote que les tocaba (solo hasta lo consumido)
WITH lotes AS (
    SELECT l.id_lote, l.id_cliente, l.id_proceso, l.valor_unitario,
           COALESCE(SUM(l.cantidad_comprada) OVER (PARTITION BY l.id_cliente, l.id_proceso ORDER BY l.fecha_compra, l.id_lote
                                                  ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) AS desde,
           SUM(l.cantidad_comprada) OVER (PARTITION BY l.id_cliente, l.id_proceso ORDER BY l.fecha_compra, l.id_lote
                                          ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS hasta
    FROM lotes_prepago l
), solicitudes AS (
    SELECT sv.id_servicio, sv.id_cliente, sv.id_proceso,
           ROW_NUMBER() OVER (PARTITION BY sv.id_cliente, sv.id_proceso ORDER BY sv.id_servicio) AS n,
           COALESCE(s.cantidad_consumida, 0) AS consumido
    FROM servicios sv
    JOIN clientes c ON c.id_cliente = sv.id_cliente AND c.tipo_cliente = 'PREPAGO'
    LEFT JOIN saldos_servicio_cliente s ON s.id_cliente = sv.id_cliente AND s.id_proceso = sv.id_proceso
    WHERE sv.id_lote_prepago IS NULL
)
UPDATE servicios sv
SET id_lote_prepago = lo.id_lote, valor_unitario_prepago = lo.valor_unitario
FROM solicitudes so
JOIN lotes lo ON lo.id_cliente = so.id_cliente AND lo.id_proceso = so.id_proceso AND so.n > lo.desde AND so.n <= lo.hasta
WHERE sv.id_servicio = so.id_servicio AND so.n <= so.consumido;

-- Reporte
INSERT INTO migracion_lotes_prepago_reporte (tipo, id_cliente, id_proceso, id_lote, cantidad, observacion)
SELECT 'LOTE', l.id_cliente, l.id_proceso, l.id_lote, l.cantidad_comprada,
       'Compra ' || o.referencia || ': ' || l.cantidad_consumida || ' consumidas de ' || l.cantidad_comprada || ' a ' || l.valor_unitario
FROM lotes_prepago l JOIN ordenes_compra o ON o.id_orden_compra = l.id_orden_compra
WHERE NOT EXISTS (SELECT 1 FROM migracion_lotes_prepago_reporte r WHERE r.tipo = 'LOTE' AND r.id_lote = l.id_lote);

-- consumo guardado que ninguna compra aprobada respalda (saldo cargado a mano, nota crédito, datos de prueba)
INSERT INTO migracion_lotes_prepago_reporte (tipo, id_cliente, id_proceso, cantidad, observacion)
SELECT 'CONSUMO_SIN_COMPRA', s.id_cliente, s.id_proceso, s.cantidad_consumida - COALESCE(l.consumido, 0),
       'El saldo dice ' || s.cantidad_consumida || ' consumidas y los lotes solo cubren ' || COALESCE(l.consumido, 0)
FROM saldos_servicio_cliente s
LEFT JOIN (SELECT id_cliente, id_proceso, SUM(cantidad_consumida) AS consumido FROM lotes_prepago GROUP BY id_cliente, id_proceso) l
       ON l.id_cliente = s.id_cliente AND l.id_proceso = s.id_proceso
WHERE s.cantidad_consumida > COALESCE(l.consumido, 0);

-- unidades compradas en el saldo que ninguna compra aprobada respalda
INSERT INTO migracion_lotes_prepago_reporte (tipo, id_cliente, id_proceso, cantidad, observacion)
SELECT 'COMPRA_SIN_SALDO', s.id_cliente, s.id_proceso, s.cantidad_comprada - COALESCE(l.comprado, 0),
       'El saldo dice ' || s.cantidad_comprada || ' compradas y las compras aprobadas suman ' || COALESCE(l.comprado, 0)
FROM saldos_servicio_cliente s
LEFT JOIN (SELECT id_cliente, id_proceso, SUM(cantidad_comprada) AS comprado FROM lotes_prepago GROUP BY id_cliente, id_proceso) l
       ON l.id_cliente = s.id_cliente AND l.id_proceso = s.id_proceso
WHERE s.cantidad_comprada <> COALESCE(l.comprado, 0);

-- solicitudes de clientes prepago que no quedaron con lote
INSERT INTO migracion_lotes_prepago_reporte (tipo, id_cliente, id_proceso, id_servicio, observacion)
SELECT 'SERVICIO_SIN_LOTE', sv.id_cliente, sv.id_proceso, sv.id_servicio, 'Solicitud prepago sin lote: no hay compra aprobada que la cubra'
FROM servicios sv JOIN clientes c ON c.id_cliente = sv.id_cliente AND c.tipo_cliente = 'PREPAGO'
WHERE sv.id_lote_prepago IS NULL
  AND NOT EXISTS (SELECT 1 FROM migracion_lotes_prepago_reporte r WHERE r.tipo = 'SERVICIO_SIN_LOTE' AND r.id_servicio = sv.id_servicio);
