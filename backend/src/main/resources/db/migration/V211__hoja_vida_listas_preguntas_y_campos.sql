-- Respuestas del candidato. Guarda el texto de la pregunta tal como la respondió: si el admin la
-- cambia o la borra después, lo declarado no se altera.
CREATE TABLE respuestas_hoja_vida (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hoja_vida BIGINT NOT NULL REFERENCES hoja_vida_evaluado (id) ON DELETE CASCADE,
    id_item      INTEGER REFERENCES items_hoja_vida (id) ON DELETE SET NULL,
    pregunta     TEXT NOT NULL,
    respuesta    BOOLEAN,
    detalle      TEXT
);
CREATE INDEX ix_respuestas_hoja_vida_hoja ON respuestas_hoja_vida (id_hoja_vida);

