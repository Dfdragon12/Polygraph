-- Hoja de vida del candidato (2026-10-13, pedido del usuario):
--  · listas que administra el admin (libreta militar, EPS, fondo de pensiones, tipo de contrato) y
--    las preguntas de declaración del candidato — todo en una sola tabla, `items_hoja_vida`;
--  · respuestas del candidato a esas preguntas;
--  · campos nuevos: expedición del documento, complemento de la dirección, visa/pasaporte Sí-No,
--    "no tengo estudios" y, por empleo, tipo de contrato, salario y llamados de atención.

CREATE TABLE items_hoja_vida (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lista       VARCHAR(30) NOT NULL,
    nombre      TEXT NOT NULL,
    descripcion TEXT,
    orden       INTEGER NOT NULL DEFAULT 0,
    activo      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_items_hoja_vida_lista
        CHECK (lista IN ('LIBRETA_MILITAR', 'EPS', 'FONDO_PENSIONES', 'TIPO_CONTRATO', 'PREGUNTA'))
);
CREATE INDEX ix_items_hoja_vida_lista ON items_hoja_vida (lista, orden);

