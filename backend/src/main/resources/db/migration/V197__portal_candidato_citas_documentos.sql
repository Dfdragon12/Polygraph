-- Portal del candidato (2026-09-28): el link sigue abierto mientras el servicio esté activo, los
-- documentos se revisan (aprobar/devolver), cada cita tiene lugar y el candidato puede sugerir
-- cuándo tiene tiempo.

-- ── 1. Link: "usado" deja de cerrar el acceso ────────────────────────────────────────────────
-- Antes usado = true significaba DOS cosas: el candidato envió el formulario, o el gestor revocó
-- el link. Ahora enviar NO cierra el acceso (sigue editando hasta que el servicio se finalice,
-- publique o cancele), así que la revocación necesita su propia marca. El vencimiento de 36 h ya
-- no aplica (fecha_expiracion queda solo como dato histórico).
ALTER TABLE links_candidato ADD COLUMN revocado BOOLEAN NOT NULL DEFAULT false;

-- Links viejos con usado = true: si la hoja de vida del candidato NO está completada, ese "usado"
-- no pudo venir de enviar el formulario (enviar la marca completada) → fue una revocación. Se
-- conservan revocados para no reabrir un link que el gestor cerró a propósito.
UPDATE links_candidato l
   SET revocado = true
  FROM servicios s
 WHERE l.id_servicio = s.id_servicio
   AND l.usado = true
   AND NOT EXISTS (SELECT 1 FROM hoja_vida_evaluado h
                    WHERE h.id_candidato = s.id_candidato AND h.completado = true);

-- ── 2. Documentos del candidato: revisión interna ───────────────────────────────────────────
-- PENDIENTE (recién cargado) → APROBADO | DEVUELTO (con motivo obligatorio). Si el candidato
-- vuelve a subir un documento devuelto, la fila se reemplaza y queda PENDIENTE otra vez.
ALTER TABLE documento_evaluado
    ADD COLUMN estado_revision      VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado_revision IN ('PENDIENTE', 'APROBADO', 'DEVUELTO')),
    ADD COLUMN observacion_revision TEXT,
    ADD COLUMN id_usuario_revision  BIGINT REFERENCES usuarios (id_usuario),
    ADD COLUMN fecha_revision       TIMESTAMP;

-- ── 3. Lugar de la cita (poligrafía / visita) ───────────────────────────────────────────────
-- Lo escribe el programador al agendar (visita: se prellena con la dirección del candidato).
-- Puede ser una dirección o "Virtual". Es lo que el candidato ve en su tarjeta de cita.
ALTER TABLE servicio_subprocesos ADD COLUMN lugar VARCHAR(300);

-- ── 4. Sugerencias de disponibilidad del candidato ──────────────────────────────────────────
-- El candidato propone 1 a 3 días con franja (mañana/tarde) + nota; le llega al programador
-- responsable de ese subproceso. Solo una PENDIENTE por subproceso (la nueva reemplaza a la
-- anterior); ATENDIDA cuando el programador la marca vista al agendar.
CREATE TABLE sugerencias_disponibilidad (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio_subproceso BIGINT       NOT NULL REFERENCES servicio_subprocesos (id) ON DELETE CASCADE,
    comentario             VARCHAR(500),
    estado                 VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ATENDIDA', 'REEMPLAZADA')),
    fecha_creacion         TIMESTAMP    NOT NULL,
    id_usuario_atendio     BIGINT       REFERENCES usuarios (id_usuario),
    fecha_atendida         TIMESTAMP
);
CREATE INDEX ix_sugerencias_subproceso ON sugerencias_disponibilidad (id_servicio_subproceso, estado);

CREATE TABLE sugerencia_disponibilidad_opciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sugerencia  BIGINT      NOT NULL REFERENCES sugerencias_disponibilidad (id) ON DELETE CASCADE,
    fecha          DATE        NOT NULL,
    franja         VARCHAR(10) NOT NULL CHECK (franja IN ('MANANA', 'TARDE', 'CUALQUIERA'))
);
CREATE INDEX ix_sugerencia_opciones ON sugerencia_disponibilidad_opciones (id_sugerencia);
