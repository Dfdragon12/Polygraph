-- Catálogo de tipos de novedad administrable desde admin/catálogo → "Tipos de novedad". Antes
-- los tipos vivían en el enum Java TipoNovedadSubproceso y agregar uno exigía tocar código y
-- redesplegar. Estructura:
--
--   categorias_novedad (1) ──< (N) tipos_novedad (1) ──< (N) tipos_novedad_roles
--                                        │
--                                        └──< (N) novedades_subproceso.id_tipo_novedad
--
-- · categorias_novedad: agrupa los tipos en la lista desplegable (Asistencia, Logística...).
-- · tipos_novedad: cada opción de "¿Qué pasó?", con su texto de ayuda para el campo Detalle.
-- · tipos_novedad_roles: a qué rol ejecutor le aparece cada tipo (N:M con el enum Rol, guardado
--   como texto igual que usuarios.rol).
-- · novedades_subproceso deja de guardar el código del enum (tipo VARCHAR) y pasa a una FK real.
--
-- Nada se borra físicamente si ya se usó: tipos y categorías se DESACTIVAN (activo=false), así
-- las novedades viejas siguen mostrando su tipo aunque ya no se ofrezca en la lista.

CREATE TABLE categorias_novedad (
    id_categoria_novedad  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave                 VARCHAR(40)  NOT NULL UNIQUE,
    nombre                VARCHAR(100) NOT NULL,
    -- Color del punto/etiqueta en pantalla: clave de la paleta del frontend
    -- (red, orange, amber, green, sky, blue, violet, slate, gray).
    color                 VARCHAR(20)  NOT NULL DEFAULT 'gray',
    orden                 INTEGER      NOT NULL DEFAULT 0,
    activo                BOOLEAN      NOT NULL DEFAULT true
);

CREATE TABLE tipos_novedad (
    id_tipo_novedad       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria_novedad  INTEGER      NOT NULL REFERENCES categorias_novedad (id_categoria_novedad),
    clave                 VARCHAR(40)  NOT NULL UNIQUE,
    nombre                VARCHAR(150) NOT NULL,
    texto_ayuda           VARCHAR(300),
    orden                 INTEGER      NOT NULL DEFAULT 0,
    activo                BOOLEAN      NOT NULL DEFAULT true
);

CREATE INDEX ON tipos_novedad (id_categoria_novedad);

CREATE TABLE tipos_novedad_roles (
    id_tipo_novedad  INTEGER     NOT NULL REFERENCES tipos_novedad (id_tipo_novedad) ON DELETE CASCADE,
    rol              VARCHAR(30) NOT NULL CHECK (rol IN ('ANALISTA_INTERNO', 'POLIGRAFISTA', 'VISITADOR')),
    PRIMARY KEY (id_tipo_novedad, rol)
);

