-- Idempotente.

CREATE TABLE IF NOT EXISTS precios_ciudad_proceso_archivo (
    id_archivo    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proceso    INTEGER        NOT NULL,
    nivel_ciudad  VARCHAR(30)    NOT NULL,
    valor         NUMERIC(15, 2) NOT NULL,
    archivado_en  TIMESTAMP      NOT NULL,
    archivado_por VARCHAR(150)   NOT NULL,
    motivo        VARCHAR(300)
);
CREATE INDEX IF NOT EXISTS ix_precios_ciudad_archivo_proceso ON precios_ciudad_proceso_archivo (id_proceso);

CREATE TABLE IF NOT EXISTS limpieza_catalogo_auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        TIMESTAMP    NOT NULL,
    usuario      VARCHAR(150) NOT NULL,
    paso         VARCHAR(40)  NOT NULL,
    id_proceso   INTEGER,
    detalle      VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS ix_limpieza_catalogo_auditoria_fecha ON limpieza_catalogo_auditoria (fecha);
