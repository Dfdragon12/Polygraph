-- TP-08: cobertura por sede o nacional (detrás del interruptor coberturaPorSede).
-- 1) ciudades.es_sede: Bogotá y Medellín quedan como sede (configurable desde Admin › Ciudades).
-- 2) servicios.cobertura_consumo: de qué bolsa salió la unidad de la solicitud (LOCAL = por sede, NACIONAL). La devolución al cancelar vuelve a esa bolsa.
-- 3) Reporte (SOLO REPORTA, no corrige nada) de servicios con aplicaPrecioCiudad incoherente con sus recargos guardados; los valores se cargan con la
--    importación de precios (TP-05).
-- No borra nada. Idempotente.

ALTER TABLE ciudades ADD COLUMN IF NOT EXISTS es_sede BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE ciudades SET es_sede = TRUE
WHERE es_sede = FALSE
  AND (translate(lower(nombre_ciudad), 'áéíóú', 'aeiou') LIKE 'bogota%' OR translate(lower(nombre_ciudad), 'áéíóú', 'aeiou') LIKE 'medellin%');

ALTER TABLE servicios ADD COLUMN IF NOT EXISTS cobertura_consumo VARCHAR(20);

CREATE TABLE IF NOT EXISTS migracion_recargos_reporte (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(40)  NOT NULL,   -- APLICA_FALSO_CON_RECARGOS, APLICA_VERDADERO_SIN_RECARGOS
    id_proceso  INTEGER      NOT NULL,
    servicio    VARCHAR(200),
    observacion VARCHAR(400),
    migrado_en  TIMESTAMP NOT NULL DEFAULT NOW()
);

-- aplica_precio_ciudad = false pero con recargos guardados: no se aplican; conviene limpiarlos o activar la casilla
INSERT INTO migracion_recargos_reporte (tipo, id_proceso, servicio, observacion)
SELECT 'APLICA_FALSO_CON_RECARGOS', p.id_proceso, p.nombre_proceso,
       'La casilla «precio por ciudad» está apagada y tiene ' || COUNT(*) || ' recargo(s) guardado(s): no se están aplicando'
FROM procesos p JOIN precios_ciudad_proceso c ON c.id_proceso = p.id_proceso AND c.valor > 0
WHERE COALESCE(p.aplica_precio_ciudad, FALSE) = FALSE
  AND NOT EXISTS (SELECT 1 FROM migracion_recargos_reporte r WHERE r.tipo = 'APLICA_FALSO_CON_RECARGOS' AND r.id_proceso = p.id_proceso)
GROUP BY p.id_proceso, p.nombre_proceso;

-- aplica_precio_ciudad = true y falta el recargo de ciudad intermedia o de municipio
INSERT INTO migracion_recargos_reporte (tipo, id_proceso, servicio, observacion)
SELECT 'APLICA_VERDADERO_SIN_RECARGOS', p.id_proceso, p.nombre_proceso,
       'La casilla «precio por ciudad» está encendida y falta el recargo de: ' ||
       CONCAT_WS(', ',
           CASE WHEN NOT EXISTS (SELECT 1 FROM precios_ciudad_proceso c WHERE c.id_proceso = p.id_proceso AND c.nivel_ciudad = 'INTERMEDIA' AND c.valor > 0)
                THEN 'ciudad intermedia' END,
           CASE WHEN NOT EXISTS (SELECT 1 FROM precios_ciudad_proceso c WHERE c.id_proceso = p.id_proceso AND c.nivel_ciudad = 'MUNICIPIO_SECUNDARIO' AND c.valor > 0)
                THEN 'municipio' END)
FROM procesos p
WHERE p.aplica_precio_ciudad = TRUE
  AND (NOT EXISTS (SELECT 1 FROM precios_ciudad_proceso c WHERE c.id_proceso = p.id_proceso AND c.nivel_ciudad = 'INTERMEDIA' AND c.valor > 0)
    OR NOT EXISTS (SELECT 1 FROM precios_ciudad_proceso c WHERE c.id_proceso = p.id_proceso AND c.nivel_ciudad = 'MUNICIPIO_SECUNDARIO' AND c.valor > 0))
  AND NOT EXISTS (SELECT 1 FROM migracion_recargos_reporte r WHERE r.tipo = 'APLICA_VERDADERO_SIN_RECARGOS' AND r.id_proceso = p.id_proceso);
