-- TP-13: alta controlada del cliente pospago (detrás del interruptor altaPospagoControlada).
-- expediente_pospago: lo que el administrador reúne en la pantalla «Convertir a pospago» (empleados y procesos declarados con soporte, estudio de crédito,
--   contrato, cupo y día de corte). Los documentos legales (RUT, Cámara de Comercio, documento del representante) NO se guardan aquí: se leen del módulo
--   Documentos que ya existe.
-- aprobaciones_pospago: quién aprobó, cuándo, con qué cupo y corte, la excepción (si la hubo, con su motivo) y una copia de lo verificado. Solo se inserta.
-- clientes_pospago.dia_corte: día del mes del corte de facturación (1 a 28).
-- No cambia ningún cliente ni quita ningún cupo. Idempotente.

ALTER TABLE clientes_pospago ADD COLUMN IF NOT EXISTS dia_corte INTEGER;

CREATE TABLE IF NOT EXISTS expediente_pospago (
    id_cliente                 INTEGER PRIMARY KEY REFERENCES clientes (id_cliente),
    empleados_declarados       INTEGER,
    soporte_empleados          VARCHAR(255),
    procesos_proyectados       INTEGER,
    soporte_procesos           VARCHAR(255),
    estudio_credito_archivo    VARCHAR(255),
    estudio_credito_fecha      DATE,
    estudio_credito_resultado  VARCHAR(20),
    estudio_credito_por        VARCHAR(150),
    contrato_archivo           VARCHAR(255),
    cupo_solicitado            NUMERIC(15, 2),
    dia_corte                  INTEGER,
    actualizado_en             TIMESTAMP,
    actualizado_por            VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS aprobaciones_pospago (
    id_aprobacion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente         INTEGER        NOT NULL REFERENCES clientes (id_cliente),
    aprobado_por       VARCHAR(150)   NOT NULL,
    aprobado_en        TIMESTAMP      NOT NULL,
    cupo               NUMERIC(15, 2) NOT NULL,
    dia_corte          INTEGER        NOT NULL,
    excepcion          BOOLEAN        NOT NULL DEFAULT FALSE,
    motivo_excepcion   VARCHAR(1000),
    requisitos         TEXT
);
CREATE INDEX IF NOT EXISTS ix_aprobaciones_pospago_cliente ON aprobaciones_pospago (id_cliente);
