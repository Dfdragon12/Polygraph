-- Cola persistente de trabajos pesados (módulo trabajos): carga masiva de solicitudes y PDF de
-- informes. Una petición HTTP pesada ya no se procesa dentro del request: se guarda aquí y
-- responde 202 con el id; el DespachadorTrabajos toma filas con FOR UPDATE SKIP LOCKED y las
-- ejecuta en pools de hilos acotados por tipo, y el frontend consulta el estado por el id.
--
--   EN_COLA ──▶ PROCESANDO ──▶ COMPLETADO
--      ▲             │
--      └─ reintento ─┤ (error reintentable y quedan intentos; disponible_desde = espera creciente)
--                    ▼
--                 FALLIDO   (la "dead letter queue": se ve y se reintenta desde Admin → Trabajos)
--
-- · parametros_json: entrada del trabajo (ids, ruta del archivo subido). Los archivos NUNCA van a
--   la BD ni a RAM: se guardan en disco (app.trabajos.directorio) y aquí solo va la ruta relativa.
-- · resultado_json: resultado pequeño (ej. resumen de la carga masiva). resultado_ruta: archivo
--   de salida (ej. el PDF), relativo a app.trabajos.directorio.
-- · error_tecnico solo lo ve el admin; mensaje_usuario es lo que ve quien lo pidió.
-- · La limpieza (LimpiezaTrabajosJob) borra filas terminadas viejas y sus archivos.

CREATE TABLE trabajos_asincronos (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                     UUID         NOT NULL UNIQUE,
    tipo                     VARCHAR(40)  NOT NULL CHECK (tipo IN ('CARGA_MASIVA', 'INFORME_PDF')),
    estado                   VARCHAR(20)  NOT NULL CHECK (estado IN ('EN_COLA', 'PROCESANDO', 'COMPLETADO', 'FALLIDO')),
    id_usuario               BIGINT       NOT NULL REFERENCES usuarios (id_usuario),
    parametros_json          TEXT         NOT NULL,
    progreso                 INTEGER      NOT NULL DEFAULT 0 CHECK (progreso BETWEEN 0 AND 100),
    intentos                 INTEGER      NOT NULL DEFAULT 0,
    max_intentos             INTEGER      NOT NULL,
    disponible_desde         TIMESTAMP    NOT NULL,
    resultado_json           TEXT,
    resultado_ruta           VARCHAR(500),
    resultado_nombre         VARCHAR(255),
    resultado_tipo_contenido VARCHAR(100),
    mensaje_usuario          VARCHAR(500),
    error_tecnico            TEXT,
    fecha_creacion           TIMESTAMP    NOT NULL,
    fecha_inicio             TIMESTAMP,
    fecha_fin                TIMESTAMP
);

-- El despachador busca por (tipo, estado) los disponibles, en orden de llegada.
CREATE INDEX ix_trabajos_cola ON trabajos_asincronos (tipo, estado, disponible_desde, id);
-- Limpieza y panel: por estado y fecha.
CREATE INDEX ix_trabajos_estado_fecha ON trabajos_asincronos (estado, fecha_fin);
CREATE INDEX ix_trabajos_usuario ON trabajos_asincronos (id_usuario);
