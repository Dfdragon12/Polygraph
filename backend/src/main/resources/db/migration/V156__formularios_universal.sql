-- Reemplaza el modelo específico de Antecedentes (verificaciones_antecedentes_legales,
-- antecedentes_consultados, catalogo_fuentes_antecedentes, plantilla_antecedentes_bloques,
-- simit/simur/runt de V157 -ya revertida-) por un modelo ÚNICO y genérico de "documento" que
-- sirve para CUALQUIER subproceso (tipos_progreso), no solo Antecedentes.
--
-- Ya no hay columnas fijas en Java por módulo (multas, comparendos, libreta_militar...) — el
-- administrador arma la plantilla de cada subproceso desde admin/catálogo → Plantilla:
--   1. Crea SECCIONES (ej: "SIMIT", "Fuentes consultadas", "Datos del documento").
--   2. Cada sección es de tipo CAMPOS (se llena una vez) o TABLA (el analista agrega tantas
--      filas como necesite — ej. una fila por fuente consultada).
--   3. Dentro de cada sección define las COLUMNAS que quiera (nombre + tipo de dato), y
--      opcionalmente, para las TABLA, unas FILAS SUGERIDAS que aparecen precargadas (ej. los
--      nombres de las fuentes que siempre se consultan) sin obligar al analista a escribirlas.
-- Los datos que el analista realmente llena quedan en formulario_datos, columna x fila.
--
-- Como esto es solo catálogo/configuración (no hay ninguna verificación real guardada todavía —
-- verificaciones_antecedentes_legales y antecedentes_consultados están vacías), se migran los
-- datos de configuración (fuentes + bloques) directo a la nueva estructura, sin conservar las
-- tablas viejas.

CREATE TABLE formularios (
    id_formulario             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio_subproceso   BIGINT NOT NULL UNIQUE REFERENCES servicio_subprocesos (id) ON DELETE CASCADE,
    fecha_creacion           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion      TIMESTAMP
);

CREATE TABLE formulario_secciones (
    id_seccion         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_progreso   INTEGER NOT NULL REFERENCES tipos_progreso (id_tipo_progreso) ON DELETE CASCADE,
    nombre             VARCHAR(150) NOT NULL,
    tipo               VARCHAR(20) NOT NULL CHECK (tipo IN ('CAMPOS', 'TABLA')),
    orden              INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_formulario_secciones_tipo_progreso ON formulario_secciones (id_tipo_progreso);

CREATE TABLE formulario_columnas (
    id_columna     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_seccion     INTEGER NOT NULL REFERENCES formulario_secciones (id_seccion) ON DELETE CASCADE,
    nombre         VARCHAR(150) NOT NULL,
    tipo_dato      VARCHAR(20) NOT NULL CHECK (tipo_dato IN ('TEXTO', 'NUMERO', 'FECHA', 'BOOLEANO')),
    orden          INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_formulario_columnas_seccion ON formulario_columnas (id_seccion);

-- Filas que ya vienen precargadas al crear un documento nuevo, para secciones tipo TABLA (ej.
-- las fuentes que siempre se consultan). El analista puede agregar filas adicionales libres
-- además de estas — ver formulario_filas.
CREATE TABLE formulario_filas_sugeridas (
    id_fila_sugerida   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_seccion         INTEGER NOT NULL REFERENCES formulario_secciones (id_seccion) ON DELETE CASCADE,
    etiqueta           VARCHAR(150) NOT NULL,
    orden              INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_formulario_filas_sugeridas_seccion ON formulario_filas_sugeridas (id_seccion);

-- Filas reales dentro de UN documento — una por cada fila sugerida que aplique, más las que el
-- analista agregue libremente.
CREATE TABLE formulario_filas (
    id_fila       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_formulario  INTEGER NOT NULL REFERENCES formularios (id_formulario) ON DELETE CASCADE,
    id_seccion    INTEGER NOT NULL REFERENCES formulario_secciones (id_seccion) ON DELETE CASCADE,
    etiqueta      VARCHAR(150) NOT NULL,
    orden         INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_formulario_filas_documento ON formulario_filas (id_formulario);

-- El valor real que el analista escribió. id_fila es NULL para secciones CAMPOS (un solo valor
-- por columna por documento); va lleno para secciones TABLA (un valor por columna por fila).
CREATE TABLE formulario_datos (
    id_dato       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_formulario  INTEGER NOT NULL REFERENCES formularios (id_formulario) ON DELETE CASCADE,
    id_columna    INTEGER NOT NULL REFERENCES formulario_columnas (id_columna) ON DELETE CASCADE,
    id_fila       INTEGER REFERENCES formulario_filas (id_fila) ON DELETE CASCADE,
    valor         TEXT
);
CREATE UNIQUE INDEX ux_formulario_datos_campo ON formulario_datos (id_formulario, id_columna) WHERE id_fila IS NULL;
CREATE UNIQUE INDEX ux_formulario_datos_fila   ON formulario_datos (id_fila, id_columna)      WHERE id_fila IS NOT NULL;

-- ── Se retira el modelo anterior, específico de Antecedentes ──
DROP TABLE IF EXISTS antecedentes_consultados;
DROP TABLE IF EXISTS verificaciones_antecedentes_legales;
DROP TABLE IF EXISTS plantilla_antecedentes_bloques;
DROP TABLE IF EXISTS catalogo_fuentes_antecedentes;

