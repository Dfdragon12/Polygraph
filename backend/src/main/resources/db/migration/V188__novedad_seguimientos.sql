-- Seguimiento de una novedad de subproceso: pueden pasar más cosas después de reportarla (ej.
-- "el candidato llamó, llega en 30 min") y, al resolverla, quien coordina puede correr la hora
-- del subproceso. Cada entrada queda aquí en orden, en vez de sobrescribir la descripción.
-- tipo: OBSERVACION (texto libre) | REPROGRAMACION (fecha_anterior -> fecha_nueva).
CREATE TABLE novedad_seguimientos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_novedad      BIGINT NOT NULL REFERENCES novedades_subproceso (id) ON DELETE CASCADE,
    tipo            VARCHAR(20) NOT NULL,
    texto           TEXT,
    fecha_anterior  TIMESTAMP,
    fecha_nueva     TIMESTAMP,
    id_autor        BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    fecha           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ON novedad_seguimientos (id_novedad);
