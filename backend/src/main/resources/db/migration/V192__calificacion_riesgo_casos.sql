-- Fase D del motor de calificación de riesgo (docs/modelo-calificacion-riesgo.md): el motor se
-- conecta a los casos reales.
--
--   servicios 1 ──< calificaciones_riesgo   (una fila vigente + historial; nunca se sobrescribe)
--   servicios 1 ──< servicio_subprocesos     (no_realizado + motivo)
--
-- · servicio_subprocesos.no_realizado: quien coordina lo marca al resolver una novedad (ej. el
--   candidato no aceptó la poligrafía). El subproceso queda CANCELADO — para el motor, todo
--   cancelado cuenta como NO_REALIZADO (no penaliza, su peso se reparte); esta marca solo deja
--   registrado que fue por esa razón, quién y cuándo.
-- · servicios.criticidad_cargo: criticidad propia del caso; NULL = usa procesos.criticidad_defecto.
-- · calificaciones_riesgo: cada recálculo que cambia el resultado agrega una fila (vigente = true)
--   y deja la anterior de historial. detalle_json guarda el registro interno completo (resultado
--   por subproceso, pesos efectivos, motivos) y la configuración usada. La decisión del gestor
--   (nivel_decidido) vive en la fila vigente; al publicar el informe queda bloqueado = true y ya
--   no se recalcula.

ALTER TABLE servicio_subprocesos
    ADD COLUMN no_realizado            BOOLEAN   NOT NULL DEFAULT false,
    ADD COLUMN motivo_no_realizado     TEXT,
    ADD COLUMN id_usuario_no_realizado BIGINT    REFERENCES usuarios (id_usuario),
    ADD COLUMN fecha_no_realizado      TIMESTAMP;

ALTER TABLE servicios
    ADD COLUMN criticidad_cargo      VARCHAR(10) CHECK (criticidad_cargo IN ('ESTANDAR', 'SENSIBLE', 'CRITICO')),
    ADD COLUMN id_usuario_criticidad BIGINT      REFERENCES usuarios (id_usuario);

CREATE TABLE calificaciones_riesgo (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio            INTEGER      NOT NULL REFERENCES servicios (id_servicio) ON DELETE CASCADE,
    vigente                BOOLEAN      NOT NULL,
    estado                 VARCHAR(20)  NOT NULL
        CHECK (estado IN ('CALCULADO', 'EN_PROCESO', 'SIN_INFORMACION', 'NO_CALIFICA')),
    puntaje_ponderado      NUMERIC(5,1),
    nivel_por_puntaje      VARCHAR(10),
    puntaje_final          NUMERIC(5,1),
    nivel_final            VARCHAR(10),
    tipo_ajuste            VARCHAR(10),
    cobertura              NUMERIC(5,2),
    requiere_revision      BOOLEAN      NOT NULL,
    criticidad             VARCHAR(10)  NOT NULL,
    version_configuracion  VARCHAR(40)  NOT NULL,
    detalle_json           TEXT         NOT NULL,
    calculado_por          BIGINT       REFERENCES usuarios (id_usuario),
    fecha_calculo          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nivel_decidido         VARCHAR(10)  CHECK (nivel_decidido IN ('BAJO', 'MEDIO', 'ALTO')),
    justificacion_decision TEXT,
    decidido_por           BIGINT       REFERENCES usuarios (id_usuario),
    fecha_decision         TIMESTAMP,
    bloqueado              BOOLEAN      NOT NULL DEFAULT false
);

CREATE INDEX ON calificaciones_riesgo (id_servicio);
-- A lo sumo una fila vigente por servicio.
CREATE UNIQUE INDEX ux_calificacion_riesgo_vigente ON calificaciones_riesgo (id_servicio) WHERE vigente;
