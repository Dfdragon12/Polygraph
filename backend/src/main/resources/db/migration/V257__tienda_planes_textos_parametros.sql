CREATE TABLE IF NOT EXISTS "parametros_tienda" (
  "clave" VARCHAR(60) PRIMARY KEY NOT NULL,
  "valor" VARCHAR(200) NOT NULL,
  "tipo" VARCHAR(10) NOT NULL,                                 -- ENTERO | DECIMAL | BOOLEANO
  "descripcion" VARCHAR(300),
  "actualizado_por" VARCHAR(150),
  "fecha_actualizacion" TIMESTAMP NOT NULL DEFAULT now()
);

-- Regla 10: todo cambio de un parámetro o interruptor queda registrado.
CREATE TABLE IF NOT EXISTS "parametros_tienda_auditoria" (
  "id_auditoria" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "clave" VARCHAR(60) NOT NULL,
  "valor_anterior" VARCHAR(200),
  "valor_nuevo" VARCHAR(200),
  "usuario" VARCHAR(150) NOT NULL,
  "fecha" TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "ix_parametros_tienda_auditoria_clave" ON "parametros_tienda_auditoria" ("clave", "fecha");

