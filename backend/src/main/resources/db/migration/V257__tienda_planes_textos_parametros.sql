CREATE TABLE IF NOT EXISTS "beneficios_plan" (
  "id_beneficio" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "id_proceso" INTEGER NOT NULL REFERENCES "procesos" ("id_proceso") ON DELETE CASCADE,
  "texto" VARCHAR(120) NOT NULL,
  "desde_unidades" INTEGER NOT NULL,
  "orden" INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT "ck_beneficios_plan_desde" CHECK ("desde_unidades" IN (1, 5, 20, 100, 200))
);
CREATE INDEX IF NOT EXISTS "ix_beneficios_plan_proceso" ON "beneficios_plan" ("id_proceso");

CREATE TABLE IF NOT EXISTS "planes_tienda" (
  "unidades" INTEGER PRIMARY KEY NOT NULL,
  "nombre" VARCHAR(60) NOT NULL,
  "visible" BOOLEAN NOT NULL DEFAULT true,
  "destacado" BOOLEAN NOT NULL DEFAULT false,
  "vigencia_meses" INTEGER,                                   -- NULL = sin vencimiento
  CONSTRAINT "ck_planes_tienda_unidades" CHECK ("unidades" IN (1, 5, 20, 100, 200))
);
-- Solo un plan puede ser "Más solicitado".
CREATE UNIQUE INDEX IF NOT EXISTS "ux_planes_tienda_destacado" ON "planes_tienda" ("destacado") WHERE "destacado";

