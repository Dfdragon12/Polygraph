-- Encabezado — uno por subproceso de Antecedentes (no por servicio: así queda conectado al
-- flujo de asignación que ya existe en servicio_subprocesos — estado, quién lo tiene, fecha
-- de completado). Incluye los campos del encabezado del PDF que no encajaban en ninguna tabla
-- de detalle (estado del documento, fecha de expedición, libreta militar, RUT) y el bloque
-- narrativo "Rama Judicial (bases privadas)", que no tiene la forma hallazgo/no-hallazgo de
-- las demás filas.
-- A propósito NO guarda quién hizo la verificación (nada de id_empleado/id_usuario aquí):
-- servicio_subprocesos.id_usuario_asignado ya es la fuente única de esa información — guardarla
-- de nuevo aquí la duplicaría y las dos podrían desincronizarse. El "Profesional encargado" del
-- documento se resuelve en tiempo de lectura a partir de esa asignación.
CREATE TABLE verificaciones_antecedentes_legales (
    id_verificacion_legal    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio_subproceso   BIGINT NOT NULL UNIQUE REFERENCES servicio_subprocesos (id) ON DELETE CASCADE,
    fecha_verificacion       DATE NOT NULL DEFAULT CURRENT_DATE,
    estado_documento         VARCHAR(50),
    fecha_expedicion         DATE,
    libreta_militar          VARCHAR(50),
    rut                      VARCHAR(100),
    observacion_rama_judicial_privada TEXT,
    observaciones_generales  TEXT,
    fecha_creacion           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion      TIMESTAMP
);

-- Una fila por fuente consultada (Procuraduría, INPEC, OFAC…) — hallazgo/no_hallazgo son
-- mutuamente excluyentes, igual que las casillas del PDF.
CREATE TABLE antecedentes_consultados (
    id_consulta            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_verificacion_legal  INTEGER NOT NULL REFERENCES verificaciones_antecedentes_legales (id_verificacion_legal) ON DELETE CASCADE,
    id_fuente               INTEGER NOT NULL REFERENCES catalogo_fuentes_antecedentes (id_fuente),
    hallazgo                BOOLEAN NOT NULL DEFAULT FALSE,
    no_hallazgo              BOOLEAN NOT NULL DEFAULT TRUE,
    observacion              TEXT,
    anexo                    VARCHAR(255),
    UNIQUE (id_verificacion_legal, id_fuente)
);

-- SIMIT / SIMUR / RUNT — un bloque fijo por verificación (no una lista), de ahí el UNIQUE.
CREATE TABLE simit (
    id_simit                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_verificacion_legal   INTEGER NOT NULL UNIQUE REFERENCES verificaciones_antecedentes_legales (id_verificacion_legal) ON DELETE CASCADE,
    multas                  VARCHAR(100),
    comparendos              VARCHAR(100),
    acuerdos_pago            VARCHAR(100),
    inmovilizaciones         VARCHAR(100),
    observacion              TEXT,
    anexo                    VARCHAR(255)
);

CREATE TABLE simur (
    id_simur                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_verificacion_legal   INTEGER NOT NULL UNIQUE REFERENCES verificaciones_antecedentes_legales (id_verificacion_legal) ON DELETE CASCADE,
    comparendo               VARCHAR(100),
    placa                    VARCHAR(50),
    fecha_infraccion         DATE,
    observacion              TEXT,
    anexo                    VARCHAR(255)
);

CREATE TABLE runt (
    id_runt                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_verificacion_legal   INTEGER NOT NULL UNIQUE REFERENCES verificaciones_antecedentes_legales (id_verificacion_legal) ON DELETE CASCADE,
    categoria                VARCHAR(100),
    estado                   VARCHAR(100),
    fecha_vencimiento        VARCHAR(100),
    observacion              TEXT,
    anexo                    VARCHAR(255)
);

CREATE INDEX ON antecedentes_consultados (id_verificacion_legal);
CREATE INDEX ON verificaciones_antecedentes_legales (id_servicio_subproceso);
