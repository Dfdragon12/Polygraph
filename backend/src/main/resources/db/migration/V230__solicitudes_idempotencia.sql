-- NS-03: llave de idempotencia al enviar una solicitud. Si el mismo usuario manda dos veces la misma llave (doble clic, reintento por red),
-- la segunda no cobra otra vez: devuelve lo que creó la primera. La restricción única también frena dos envíos simultáneos.
-- Solo agrega una tabla; no toca datos.
CREATE TABLE IF NOT EXISTS solicitudes_idempotencia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   BIGINT      NOT NULL,
    clave        VARCHAR(80) NOT NULL,
    ids_servicios VARCHAR(500),
    creada_en    TIMESTAMP   NOT NULL DEFAULT NOW(),
    CONSTRAINT ux_solicitudes_idempotencia UNIQUE (id_usuario, clave)
);
