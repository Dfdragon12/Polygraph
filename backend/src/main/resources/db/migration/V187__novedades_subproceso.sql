-- Novedades que reporta quien ejecuta un subproceso (analista/poligrafista/visitador) — p.ej.
-- "el candidato nunca llegó", "dirección errada", "fuente no disponible". Cada novedad queda
-- ABIERTA hasta que el gestor/programador que coordina el servicio la marque RESUELTA con una
-- respuesta. No cambia el estado del subproceso: solo deja el registro y dispara notificaciones.
-- tipo: código de TipoNovedadSubproceso (enum Java, sin tabla de catálogo — mismo criterio que
-- estado_confirmacion en historial_llamadas_confirmacion).
CREATE TABLE novedades_subproceso (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio_subproceso  BIGINT NOT NULL REFERENCES servicio_subprocesos (id) ON DELETE CASCADE,
    tipo                    VARCHAR(40) NOT NULL,
    descripcion             TEXT NOT NULL,
    id_registrado_por       BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    fecha_registro          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado                  VARCHAR(20) NOT NULL DEFAULT 'ABIERTA',
    respuesta               TEXT,
    id_resuelta_por         BIGINT REFERENCES usuarios (id_usuario),
    fecha_resolucion        TIMESTAMP
);

CREATE INDEX ON novedades_subproceso (id_servicio_subproceso);
