-- NS-04: cancelar una solicitud devuelve lo que costó.
--  · servicios.cobro_devuelto_en: marca (no se devuelve dos veces). Prepago: la unidad vuelve al mismo lote; pospago: el cupo vuelve y el cargo no se factura.
--  · movimientos_credito_pospago.anulado_en: el cargo de una solicitud cancelada NO entra en la factura (no se borra).
-- Corrección de datos (reporte en migracion_devolucion_cobro_reporte): las solicitudes YA canceladas cuyo cobro nunca se devolvió.
--  · Prepago: la unidad vuelve a la bolsa (y a su lote si lo tiene).
--  · Pospago sin facturar: se anula el cargo y vuelve el cupo.
--  · Pospago ya facturado: NO se toca (hace falta una nota crédito); queda en el reporte.
-- Idempotente: lo que ya tiene cobro_devuelto_en no se repite.

ALTER TABLE servicios ADD COLUMN IF NOT EXISTS cobro_devuelto_en TIMESTAMP;
ALTER TABLE movimientos_credito_pospago ADD COLUMN IF NOT EXISTS anulado_en TIMESTAMP;

CREATE TABLE IF NOT EXISTS migracion_devolucion_cobro_reporte (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio INTEGER NOT NULL,
    id_cliente  INTEGER,
    modalidad   VARCHAR(10),
    accion      VARCHAR(40) NOT NULL,   -- UNIDAD_DEVUELTA, UNIDAD_DEVUELTA_SIN_LOTE, CUPO_DEVUELTO, YA_FACTURADO, SIN_COBRO
    valor       NUMERIC(15, 2),
    migrado_en  TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Prepago: la unidad vuelve a la bolsa y, si la solicitud tiene lote, a ese lote
UPDATE lotes_prepago l SET cantidad_consumida = GREATEST(l.cantidad_consumida - x.n, 0)
FROM (SELECT s.id_lote_prepago AS id_lote, COUNT(*) AS n
      FROM servicios s JOIN clientes c ON c.id_cliente = s.id_cliente AND c.tipo_cliente = 'PREPAGO'
      WHERE s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL AND s.id_lote_prepago IS NOT NULL
      GROUP BY s.id_lote_prepago) x
WHERE x.id_lote = l.id_lote;
INSERT INTO migracion_devolucion_cobro_reporte (id_servicio, id_cliente, modalidad, accion, valor)
SELECT s.id_servicio, s.id_cliente, 'PREPAGO',
       CASE WHEN s.id_lote_prepago IS NULL THEN 'UNIDAD_DEVUELTA_SIN_LOTE' ELSE 'UNIDAD_DEVUELTA' END, s.valor_unitario_prepago
FROM servicios s JOIN clientes c ON c.id_cliente = s.id_cliente AND c.tipo_cliente = 'PREPAGO'
JOIN saldos_servicio_cliente sa ON sa.id_cliente = s.id_cliente AND sa.id_proceso = s.id_proceso AND sa.cantidad_consumida > 0
WHERE s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL;

-- la bolsa: tantas unidades como solicitudes canceladas sin devolver, sin pasar de lo consumido
WITH por_devolver AS (
    SELECT s.id_cliente, s.id_proceso, COUNT(*) AS n
    FROM servicios s JOIN clientes c ON c.id_cliente = s.id_cliente AND c.tipo_cliente = 'PREPAGO'
    WHERE s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL GROUP BY s.id_cliente, s.id_proceso
)
UPDATE saldos_servicio_cliente sa
SET cantidad_consumida = sa.cantidad_consumida - LEAST(p.n, sa.cantidad_consumida),
    cantidad_disponible = sa.cantidad_disponible + LEAST(p.n, sa.cantidad_consumida),
    fecha_actualizacion = NOW()
FROM por_devolver p WHERE p.id_cliente = sa.id_cliente AND p.id_proceso = sa.id_proceso;

-- Pospago sin facturar: se anula el cargo y vuelve el cupo
INSERT INTO migracion_devolucion_cobro_reporte (id_servicio, id_cliente, modalidad, accion, valor)
SELECT s.id_servicio, s.id_cliente, 'POSPAGO',
       CASE WHEN m.id_factura IS NULL THEN 'CUPO_DEVUELTO' ELSE 'YA_FACTURADO' END, m.monto_total
FROM servicios s JOIN movimientos_credito_pospago m ON m.id_servicio = s.id_servicio AND m.anulado_en IS NULL
WHERE s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL;

UPDATE clientes_pospago cp SET credito_disponible = cp.credito_disponible + x.total
FROM (SELECT m.id_cliente, SUM(m.monto_total) AS total
      FROM movimientos_credito_pospago m JOIN servicios s ON s.id_servicio = m.id_servicio
      WHERE s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL AND m.anulado_en IS NULL AND m.id_factura IS NULL
      GROUP BY m.id_cliente) x
WHERE x.id_cliente = cp.id_cliente;

UPDATE movimientos_credito_pospago m SET anulado_en = NOW()
FROM servicios s WHERE s.id_servicio = m.id_servicio AND s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL
  AND m.anulado_en IS NULL AND m.id_factura IS NULL;

-- marca de las que ya quedaron resueltas (las pospago ya facturadas NO: siguen pendientes de una nota crédito)
UPDATE servicios s SET cobro_devuelto_en = NOW()
WHERE s.estado = 'CANCELADO' AND s.cobro_devuelto_en IS NULL
  AND NOT EXISTS (SELECT 1 FROM movimientos_credito_pospago m WHERE m.id_servicio = s.id_servicio AND m.anulado_en IS NULL);
